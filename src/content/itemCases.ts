export type ItemCaseId = keyof typeof ITEM_CASES;
export const isItemCaseId = (value: unknown): value is ItemCaseId =>
  typeof value === 'string' && Object.hasOwn(ITEM_CASES, value);
export const itemCase = (id?: ItemCaseId): ItemCase =>
  ITEM_CASES[id ?? 'normal'];
export function caseApplies(id: ItemCaseId, kind: Kind, marketId?: MarketId) {
  const rule = itemCase(id);
  return (
    (!rule.kinds || rule.kinds.includes(kind)) &&
    (!rule.markets || rule.markets.includes(marketId ?? 'street'))
  );
}
