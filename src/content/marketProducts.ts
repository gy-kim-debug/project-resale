type Row = readonly [string, number, number];
function group(
  category: ProductCategory,
  rows: readonly Row[],
): MarketProduct[] {
  const info = PRODUCT_CATEGORIES[category];
  return rows.map(([title, min, max]) => ({
    title,
    kind: info.kind,
    category,
    min,
    max,
    description: `${title} 판매합니다.`,
  }));
}
